console.log("DAY 5: LOOPS");

console.log("FOR LOOP");

console.log("Example 1: Print Numbers");
for (let i = 1; i <= 5; i++) {
    console.log(i);
}

console.log("Example 2: Print Names");
for (let i = 1; i <= 5; i++) {
    console.log("Ali");
}

console.log("Example 3: Count to 10");
for (let i = 1; i <= 10; i++) {
    console.log(i);
}

console.log("Example 4: Table of 2");
for (let i = 1; i <= 5; i++) {
    console.log("2 x " + i + " = " + (2 * i));
}

console.log("Example 5: Print Fruits");
for (let i = 1; i <= 3; i++) {
    console.log("Apple");
}


console.log("WHILE LOOP");

console.log("Example 1: Print Numbers");
let a = 1;
while (a <= 5) {
    console.log(a);
    a++;
}

console.log("Example 2: Print Names");
let b = 1;
while (b <= 3) {
    console.log("Ahmed");
    b++;
}

console.log("Example 3: Count to 10");
let c = 1;
while (c <= 10) {
    console.log(c);
    c++;
}

console.log("Example 4: Table of 3");
let d = 1;
while (d <= 5) {
    console.log("3 x " + d + " = " + (3 * d));
    d++;
}

console.log("Example 5: Print Fruits");
let e = 1;
while (e <= 3) {
    console.log("Mango");
    e++;
}


console.log("DO WHILE LOOP");

console.log("Example 1: Print Numbers");
let f = 1;
do {
    console.log(f);
    f++;
} while (f <= 5);

console.log("Example 2: Print Names");
let g = 1;
do {
    console.log("Hassan");
    g++;
} while (g <= 3);

console.log("Example 3: Count to 10");
let h = 1;
do {
    console.log(h);
    h++;
} while (h <= 10);

console.log("Example 4: Table of 4");
let j = 1;
do {
    console.log("4 x " + j + " = " + (4 * j));
    j++;
} while (j <= 5);

console.log("Example 5: Print Fruits");
let k = 1;
do {
    console.log("Banana");
    k++;
} while (k <= 3);